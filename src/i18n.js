export function t(locale, key) {
  return UI[locale]?.[key] ?? UI['zh-CN'][key] ?? key
}

export function pickLocalized(map, locale) {
  if (!map || typeof map !== 'object') return ''
  return map[locale] ?? map['zh-CN'] ?? map.en ?? Object.values(map)[0] ?? ''
}
